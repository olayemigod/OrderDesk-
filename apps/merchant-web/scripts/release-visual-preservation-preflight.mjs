import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = (name) => readFileSync(new URL('../src/' + name, import.meta.url), 'utf8');
const app = read('MerchantAuth.tsx');
assert.ok(app.includes("type={visible ? 'text' : 'password'}"));
assert.ok(app.includes('aria-pressed={visible}'));
assert.ok(app.includes('type="button"\n        className="password-toggle"'));
assert.ok(app.includes('visible={showPassword}'));
assert.ok(app.includes('visible={showConfirmPassword}'));
assert.ok(app.includes('setShowPassword(false); setShowConfirmPassword(false);'));
assert.ok(read('MerchantApp.tsx').includes('<MerchantAuth'));
assert.ok(read('main.tsx').includes("import './merchant-auth.css'"));
const management = read('ManagementPage.tsx');
const settings = read('SettingsManagement.tsx');
assert.ok(!management.includes('PaymentBranchManagement'));
const payment = settings.indexOf('id="settings-panel-payments"');
const availability = settings.indexOf('<PaymentBranchManagement tenantId={tenantId} />');
assert.ok(payment >= 0 && availability > payment);
assert.ok(settings.slice(payment, availability).includes("hidden={activeTab !== 'payments'}"));
assert.ok(!management.includes('SetupSchedulingManagement'), 'Settings must never mount the dedicated commercial setup page');
assert.ok(read('MerchantApp.tsx').includes("page === 'setup' && <SetupSchedulingManagement"));
const vercel = JSON.parse(readFileSync(new URL('../vercel.json', import.meta.url), 'utf8'));
const csp = vercel.headers.flatMap(rule => rule.headers).find(header => header.key === 'Content-Security-Policy').value;
const imageSources = csp.split(';').map(value => value.trim()).find(value => value.startsWith('img-src ')).split(/\s+/).slice(1);
assert.deepEqual(imageSources, ["'self'", 'data:', 'https://*.supabase.co/storage/v1/object/public/business-logos/']);
assert.ok(csp.includes("script-src 'self'") && csp.includes("frame-ancestors 'none'"));
assert.ok(settings.includes('onError={() => setFailedLogoUrl(profile.logoUrl)}'));
console.log('Merchant release visual preservation preflight passed.');
